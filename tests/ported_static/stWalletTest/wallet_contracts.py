def mapping_slot(key: int | Address | Hash, base: int) -> int:
    """Return the storage slot of `key` in the mapping at slot `base`."""
    return int.from_bytes(
        Bytes(Hash(key, left_padding=True) + Hash(base)).keccak256(), "big"
    )


def pending_index_element_slot(index: int) -> int:
    """Return the storage slot of `m_pendingIndex[index]`."""
    return int.from_bytes(Hash(PENDING_INDEX_SLOT).keccak256(), "big") + index


def owners_storage(required: int, owners: Sequence[Address]) -> dict:
    """Return the storage of a wallet with `owners` and `required`."""
    storage: dict = {REQUIRED_SLOT: required, OWNER_COUNT_SLOT: len(owners)}
    for index, owner in enumerate(owners, start=1):
        storage[FIRST_OWNER_SLOT + index - 1] = owner
        storage[mapping_slot(owner, OWNER_INDEX_MAP)] = index
    return storage
