"""
Test fixed pseudo-random bytecode sequences run in a called frame.

The original tests were written by Ori Pomerantz.

Ported from:
state_tests/VMTests/vmTests/randomFiller.yml

@manually-enhanced: Do not overwrite. Each `RandomCode` scenario is one of
the generated bytecode sequences kept from the old VMTests, spelled out
opcode by opcode. A `caller` calls a `callee` holding the sequence with
`CALLEE_GAS` and stores the call's success flag over a sentinel. A
sequence that needs a stack item it does not have halts exceptionally,
so the call fails and burns all the gas it was given. A sequence that
ends in a PUSH cut short by the end of the code reads the missing
immediate bytes as zeros and stops normally. The receipt's gas used is
derived from the framework gas calculation, so it also checks how much
gas the callee consumed. The original only checked the sender's nonce,
which held whether the sequences ran or not.
"""

from enum import StrEnum

import pytest
from execution_testing import (
    Account,
    Alloc,
    Bytecode,
    Fork,
    Op,
    StateTestFiller,
    Transaction,
    TransactionReceipt,
)
from execution_testing.vm import Opcode

REFERENCE_SPEC_GIT_PATH = "N/A"
REFERENCE_SPEC_VERSION = "N/A"

pytestmark = [
    pytest.mark.ported_from(
        ["state_tests/VMTests/vmTests/randomFiller.yml"],
    ),
    pytest.mark.valid_from("Frontier"),
]

SENTINEL = 0x0BAD
RESULT_SLOT = 0
# Explicit, so the call does not ask for more gas than is left before
# EIP-150 lets it forward all but 1/64th.
CALLEE_GAS = 0x10000


class RandomCode(StrEnum):
    """A pseudo-random bytecode sequence, named after what it exercises."""

    SWAP8_UNDERFLOW = "swap8_underflow"
    BLOCKHASH_UNDERFLOW_BEFORE_SSTORE = "blockhash_underflow_before_sstore"
    BLOCKHASH_UNDERFLOW_BEFORE_PUSH14 = "blockhash_underflow_before_push14"
    TRUNCATED_PUSH24 = "truncated_push24"
    TRUNCATED_PUSH6 = "truncated_push6"
    BLOCKHASH_UNDERFLOW = "blockhash_underflow"


def truncated_push(opcode: Opcode, immediate: bytes) -> Bytecode:
    """Return a PUSH whose immediate is cut short by the end of the code."""
    assert len(immediate) < opcode.data_portion_length
    return opcode + immediate


def random_code(scenario: RandomCode) -> Bytecode:
    """Return the bytecode sequence of `scenario`."""
    match scenario:
        case RandomCode.SWAP8_UNDERFLOW:
            # Eight block fields on the stack, one short of what SWAP8
            # needs.
            return (
                Op.NUMBER * 2
                + Op.TIMESTAMP
                + Op.PREVRANDAO
                + Op.TIMESTAMP
                + Op.PREVRANDAO
                + Op.GASLIMIT * 2
                + Op.SWAP8
            )
        case RandomCode.BLOCKHASH_UNDERFLOW_BEFORE_SSTORE:
            # BLOCKHASH on an empty stack, so the CODECOPY, SELFDESTRUCT
            # and SSTORE after it never run.
            return (
                Op.BLOCKHASH
                + Op.GASLIMIT
                + Op.BLOCKHASH
                + Op.COINBASE
                + Op.GASLIMIT * 2
                + Op.PREVRANDAO
                + Op.COINBASE
                + Op.CALLVALUE
                + Op.CODECOPY
                + Op.DUP8
                + Op.SELFDESTRUCT
                + Op.CALLDATACOPY
                + Op.CALLDATALOAD
                + Op.DIV
                + Op.ADDRESS
                + Op.SSTORE
            )
        case RandomCode.BLOCKHASH_UNDERFLOW_BEFORE_PUSH14:
            # BLOCKHASH on an empty stack, ahead of a truncated PUSH14.
            return (
                Op.BLOCKHASH * 2
                + Op.GASLIMIT
                + Op.SWAP2
                + Op.NUMBER
                + Op.BLOCKHASH
                + Op.COINBASE
                + Op.PREVRANDAO
                + Op.DUP1
                + Op.SWAP8
                + Op.MSIZE
                + Op.DUP9
                + truncated_push(Op.PUSH14, bytes.fromhex("608f"))
            )
        case RandomCode.TRUNCATED_PUSH24:
            return truncated_push(
                Op.PUSH24, bytes.fromhex("45414245403745f31387900a8d55")
            )
        case RandomCode.TRUNCATED_PUSH6:
            return truncated_push(Op.PUSH6, bytes.fromhex("424555"))
        case RandomCode.BLOCKHASH_UNDERFLOW:
            return Op.BLOCKHASH + Op.COINBASE
    raise ValueError(f"Unknown scenario: {scenario}")


@pytest.mark.parametrize("scenario", list(RandomCode), ids=str)
def test_random(
    state_test: StateTestFiller,
    pre: Alloc,
    fork: Fork,
    scenario: RandomCode,
) -> None:
    """Call a pseudo-random bytecode sequence and check how it ends."""
    callee_code = random_code(scenario)
    # The code runs straight through from an empty stack, so it halts
    # exceptionally exactly when some opcode pops more than it finds.
    halts = callee_code.min_stack_height > 0
    callee = pre.deploy_contract(code=callee_code)

    succeeded = int(not halts)
    caller_code = (
        Op.SSTORE(
            RESULT_SLOT,
            Op.CALL(gas=CALLEE_GAS, address=callee),
            original_value=SENTINEL,
            new_value=succeeded,
        )
        + Op.STOP
    )
    caller = pre.deploy_contract(
        code=caller_code, storage={RESULT_SLOT: SENTINEL}
    )

    # An exceptional halt consumes all the gas the call forwarded.
    callee_gas_used = CALLEE_GAS if halts else callee_code.gas_cost(fork)
    executed = (
        fork.transaction_intrinsic_cost_calculator()()
        + caller_code.gas_cost(fork)
        + callee_gas_used
    )
    refund = min(
        caller_code.refund(fork), executed // fork.max_refund_quotient()
    )
    tx = Transaction(
        sender=pre.fund_eoa(),
        to=caller,
        protected=fork.supports_protected_txs(),
        expected_receipt=TransactionReceipt(
            cumulative_gas_used=executed - refund
        ),
    )

    post = {caller: Account(storage={RESULT_SLOT: succeeded})}
    state_test(pre=pre, post=post, tx=tx)
