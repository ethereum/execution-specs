@dataclass(frozen=True)
class TargetedAccount:
    """
    A Mainnet account whose nonce is bumped to one at the fork block.

    `storage_keys` are the account's non-zero Mainnet storage slots, from
    the `targeted-accounts.json` asset of the EIP. `creator` and
    `creation_nonce` are the address and nonce whose `CREATE` derived the
    account on Mainnet, so that `compute_create_address(creator,
    creation_nonce)` is `address`.
    """

    address: int
    storage_keys: Tuple[int, ...]
    creator: int
    creation_nonce: int


